"""Convert a finished 48x64 walk sheet (<src>_sheet.png, RGBA, rows down/left/right/up, columns stand/stride/stand/stride) into a
pxl source file (github.com/crsolver/claude-pxl, "pixel art as code"), so single pixels can be fixed as text and the result exported
as sprites, walk anims (strip + GIF + Aseprite-style JSON) and a sprite sheet.
Palette: the sheet's opaque colours, dark to light, keys 0-9a-zA-Z by index (use([...])). Each frame is a sprite owens_<dir>_<col>,
48x64, drawn with grid(x, y, ...) at its opaque bounding box so positions stay exact (part _raw_<dir>_<col>). The exported
frames owens_<dir>_<col> live in owens_fixes.px.js (created once, then hand-edited): base = the raw frame, plus fixes.
Usage: python sheet_to_pxl.py <src> [--out pxl/owens_walk.px.js]
Build: <node22> <pxl>/bin/pxl.js build work/pxl/owens_walk.px.js   (see README: pxl)
"""
import argparse, os
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
import settings
D = settings.WORK
KEYS = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"
DIRS = ["down", "left", "right", "up"]
CW, CH = 48, 64


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("src"); ap.add_argument("--out", default=os.path.join(settings.WORK, "pxl", "owens_walk.px.js"))
    a = ap.parse_args()
    s = np.asarray(Image.open(os.path.join(D, a.src + "_sheet.png")).convert("RGBA"))
    op = s[..., 3] > 127
    cols = np.unique(s[..., :3][op], axis=0)
    lum = cols @ np.array([0.299, 0.587, 0.114])
    cols = cols[np.argsort(lum)]
    if len(cols) > len(KEYS):
        raise SystemExit(f"{len(cols)} colours, pxl custom palettes hold {len(KEYS)}")
    key = {tuple(c): KEYS[i] for i, c in enumerate(cols)}
    hexes = ", ".join(f'"#{c[0]:02x}{c[1]:02x}{c[2]:02x}"' for c in cols)
    out = [f"// Generated by sheet_to_pxl.py from {a.src}_sheet.png. Do not edit: put fixes in owens_fixes.px.js.",
           f"use([{hexes}])", ""]
    for r, d in enumerate(DIRS):
        for c in range(4):
            cell = s[r * CH:(r + 1) * CH, c * CW:(c + 1) * CW]; m = cell[..., 3] > 127
            ys, xs = np.nonzero(m); y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
            rows = ["".join(key[tuple(cell[y, x, :3])] if m[y, x] else "." for x in range(x0, x1)) for y in range(y0, y1)]
            body = "\n".join("  " + row for row in rows)
            out.append(f'sprite("_raw_{d}_{c}", {{ w: {CW}, h: {CH} }}, grid({x0}, {y0}, `\n{body}`))')
    out += ["", "// The exported frames owens_<dir>_<col> are defined in owens_fixes.px.js: base = the raw frame, plus pixel fixes.",
            'include("owens_fixes.px.js")', ""]
    for d in DIRS:
        out.append(f'anim("walk_{d}", {{ w: {CW}, h: {CH}, fps: 6 }}, ' + ", ".join(f'frame(stamp("owens_{d}_{c}", 0, 0))' for c in range(4)) + ")")
    out += ["", 'sheet("owens_walk_sheet", ["owens_*"], { cols: 4 })', ""]
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    open(a.out, "w", encoding="utf-8").write("\n".join(out))
    fixes = os.path.join(os.path.dirname(a.out), "owens_fixes.px.js")
    if not os.path.exists(fixes) or "globalThis.FIX" in open(fixes, encoding="utf-8").read():
        lines = ["// Hand fixes on top of the generated raw frames (sheet_to_pxl.py never overwrites this file).",
                 "// Each exported frame = its raw frame (base) + ops, e.g. recolor({ 1: \"N\" }, [22, 20, 3, 9]) or grid(x, y, `...`).", ""]
        lines += [f'sprite("owens_{d}_{c}", {{ base: "_raw_{d}_{c}" }})' for d in DIRS for c in range(4)]
        open(fixes, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(a.out, len(cols), "colours")


if __name__ == "__main__":
    main()
